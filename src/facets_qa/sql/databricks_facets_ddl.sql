-- Databricks (Unity Catalog / Delta) version of the mock Facets schema.
-- __SCHEMA__ is replaced with <catalog>.<schema> at runtime (e.g. workspace.facets_qa).

CREATE SCHEMA IF NOT EXISTS __SCHEMA__ COMMENT 'Mock Facets tables + QA results for EDI test automation practice';

CREATE TABLE IF NOT EXISTS __SCHEMA__.cmc_sbsb_subsc (
    SBSB_CK BIGINT NOT NULL, GRGR_CK BIGINT NOT NULL, SBSB_ID STRING NOT NULL,
    SBSB_LAST_NAME STRING, SBSB_FIRST_NAME STRING, SBSB_ORIG_EFF_DT DATE
) USING DELTA COMMENT 'Facets subscriber (mock)';

CREATE TABLE IF NOT EXISTS __SCHEMA__.cmc_meme_member (
    MEME_CK BIGINT NOT NULL, SBSB_CK BIGINT NOT NULL, MEME_SFX INT NOT NULL, MEME_REL STRING,
    MEME_LAST_NAME STRING, MEME_FIRST_NAME STRING, MEME_BIRTH_DT DATE, MEME_SEX STRING
) USING DELTA COMMENT 'Facets member (mock)';

CREATE TABLE IF NOT EXISTS __SCHEMA__.cmc_mepe_prcs_elig (
    MEME_CK BIGINT NOT NULL, CSPD_CAT STRING NOT NULL, MEPE_EFF_DT DATE NOT NULL, MEPE_TERM_DT DATE NOT NULL,
    MEPE_ELIG_IND STRING NOT NULL, CSPI_ID STRING, PDPD_ID STRING
) USING DELTA COMMENT 'Facets member eligibility spans (mock)';

CREATE TABLE IF NOT EXISTS __SCHEMA__.cmc_prpr_prov (
    PRPR_ID STRING NOT NULL, PRPR_NPI STRING NOT NULL, PRPR_NAME STRING, MCTN_ID STRING
) USING DELTA COMMENT 'Facets provider (mock)';

CREATE TABLE IF NOT EXISTS __SCHEMA__.cmc_clcl_claim (
    CLCL_ID STRING NOT NULL, CLCL_PA_ACCT_NO STRING, CLCL_CL_TYPE STRING, CLCL_CL_SUB_TYPE STRING,
    CLCL_CUR_STS STRING, MEME_CK BIGINT, PRPR_ID STRING, CLCL_TOT_CHG DECIMAL(11,2),
    CLCL_LOW_SVC_DT DATE, CLCL_HIGH_SVC_DT DATE, PSCD_ID STRING, CLCL_INPUT_DT DATE
) USING DELTA COMMENT 'Facets claim header (mock)';

CREATE TABLE IF NOT EXISTS __SCHEMA__.cmc_cdml_cl_line (
    CLCL_ID STRING NOT NULL, CDML_SEQ_NO INT NOT NULL, IPCD_ID STRING,
    CDML_MOD1 STRING, CDML_MOD2 STRING, CDML_MOD3 STRING, CDML_MOD4 STRING, RCRC_ID STRING,
    CDML_CHG_AMT DECIMAL(11,2), CDML_UNITS DECIMAL(9,3), CDML_FROM_DT DATE, CDML_TO_DT DATE
) USING DELTA COMMENT 'Facets claim line (mock)';

CREATE TABLE IF NOT EXISTS __SCHEMA__.cmc_clhp_hosp (
    CLCL_ID STRING NOT NULL, CLHP_FAC_TYPE STRING, CLHP_BILL_CLASS STRING, CLHP_FREQUENCY STRING,
    CLHP_ADM_DT DATE, CLHP_DC_DT DATE, CLHP_ADM_TYP STRING, CLHP_DC_STAT STRING
) USING DELTA COMMENT 'Facets hospital claim data (mock)';

CREATE TABLE IF NOT EXISTS __SCHEMA__.elig_test_results (
    run_id STRING, run_ts TIMESTAMP, meme_ck BIGINT, member_id STRING, scenario STRING,
    service_date DATE, trace_number STRING, expected_status STRING, actual_status STRING,
    expected_aaa STRING, actual_aaa STRING, result STRING, failure_reason STRING,
    attempts INT, latency_ms BIGINT, worker_id INT
) USING DELTA COMMENT '270/271 eligibility test results';

CREATE TABLE IF NOT EXISTS __SCHEMA__.claim_test_results (
    run_id STRING, run_ts TIMESTAMP, scenario STRING, claim_type STRING, polarity STRING,
    clcl_id STRING, result STRING, detail STRING, x12 STRING
) USING DELTA COMMENT '837P/837I claims test results';
